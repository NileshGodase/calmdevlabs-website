import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = resolve(root, 'node_modules', 'lucide-static', 'icons');
const outFile = resolve(root, 'src', 'partials', 'sprite.html');

/**
 * Icons used across the site. Names must match lucide-static icon filenames
 * (kebab-case, without extension). Run `npm run build:icons` after changing.
 */
const ICONS = [
  'menu',
  'x',
  'arrow-right',
  'arrow-up-right',
  'mail',
  'check',
  'smartphone',
  'globe',
  'database',
  'server',
  'wrench',
  'users',
  'briefcase',
  'shield-check',
  'code',
  'send',
  'map-pin',
  'file-text',
  'clock',
  'layers',
  'terminal',
  'building-2',
];

if (!existsSync(iconsDir)) {
  console.error(`lucide-static not found at ${iconsDir}. Run "npm install" first.`);
  process.exit(1);
}

const available = new Set(readdirSync(iconsDir).map((f) => f.replace(/\.svg$/, '')));

const symbols = ICONS.map((name) => {
  if (!available.has(name)) {
    console.warn(`warning: icon "${name}" not found in lucide-static, skipped`);
    return '';
  }
  const svg = readFileSync(resolve(iconsDir, `${name}.svg`), 'utf8');
  const openTag = svg.match(/<svg[^>]*>/)?.[0] ?? '<svg>';
  const attrs = ['viewBox="0 0 24 24"'];
  for (const attr of ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']) {
    const m = openTag.match(new RegExp(`${attr}="([^"]*)"`));
    if (m) attrs.push(`${attr}="${m[1]}"`);
  }
  const inner = svg.replace(/<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  return `  <symbol id="icon-${name}" ${attrs.join(' ')}>\n    ${inner}\n  </symbol>`;
}).filter(Boolean);

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `<!-- Generated by npm run build:icons — do not edit by hand. -->\n<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true" focusable="false">\n${symbols.join('\n')}\n</svg>\n`,
);
console.log(`wrote ${outFile} (${symbols.length} icons)`);
